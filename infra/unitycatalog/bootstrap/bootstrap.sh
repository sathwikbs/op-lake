#!/usr/bin/env bash
#
# Bootstraps the Unity Catalog governance layer:
#   1. analytics catalog + bronze/silver/gold schemas (medallion)
#   2. Sample users (engineer, analyst) mirroring the Keycloak realm
#   3. RBAC grants demonstrating least-privilege roles
#
# Idempotent: re-running is safe (creates are guarded).
#
set -uo pipefail

cd /home/unitycatalog

CONF=/home/unitycatalog/etc/conf
UC_URI="${UC_URI:-http://unitycatalog:8080}"
CATALOG="${UC_CATALOG:-analytics}"
BUCKET="${LAKEHOUSE_BUCKET:-lakehouse}"

echo ">> Waiting for admin token.txt to be generated by the UC server..."
for _ in $(seq 1 60); do
  [ -s "${CONF}/token.txt" ] && break
  sleep 2
done
if [ ! -s "${CONF}/token.txt" ]; then
  echo "!! token.txt not found - is server.authorization enabled? Aborting." >&2
  exit 1
fi
TOKEN="$(cat "${CONF}/token.txt")"

uc() { bin/uc --server "${UC_URI}" --auth_token "${TOKEN}" "$@"; }

echo ">> Creating catalog + medallion schemas"
uc catalog create --name "${CATALOG}" --comment "Governed analytics lakehouse" 2>/dev/null || true
for schema in bronze silver gold; do
  uc schema create --catalog "${CATALOG}" --name "${schema}" \
    --comment "${schema} layer" 2>/dev/null || true
done

echo ">> Creating users (must match Keycloak realm emails)"
uc user create --name "Data Engineer" --email engineer@platform.local 2>/dev/null || true
uc user create --name "Data Analyst"  --email analyst@platform.local  2>/dev/null || true

grant() {
  # grant <securable_type> <name> <privilege> <principal>
  uc permission create --securable_type "$1" --name "$2" \
    --privilege "$3" --principal "$4" 2>/dev/null || true
}

echo ">> RBAC: engineer = full builder on all layers"
grant catalog "${CATALOG}" "USE CATALOG" engineer@platform.local
for schema in bronze silver gold; do
  grant schema "${CATALOG}.${schema}" "USE SCHEMA"   engineer@platform.local
  grant schema "${CATALOG}.${schema}" "CREATE TABLE" engineer@platform.local
  grant schema "${CATALOG}.${schema}" "MODIFY"       engineer@platform.local
  grant schema "${CATALOG}.${schema}" "SELECT"       engineer@platform.local
done

echo ">> RBAC: analyst = read-only on the gold layer"
grant catalog "${CATALOG}"        "USE CATALOG" analyst@platform.local
grant schema  "${CATALOG}.gold"   "USE SCHEMA"  analyst@platform.local
grant schema  "${CATALOG}.gold"   "SELECT"      analyst@platform.local

# Automation service accounts are NOT granted here. The iam-reconciler
# (`ensure-sas`) owns their Keycloak clients, UC principals and grants from
# personas.yaml. Granting them builder rights here re-escalated the default
# automation SA (catalog-only by design) on every `docker compose up` that ran
# this one-shot after the reconciler had started (smoke check G6).

echo ">> Bootstrap complete. Current catalog/schema layout:"
uc schema list --catalog "${CATALOG}" || true
